/*
  Паспорт рамы: какие поля есть, как они подписаны, с каким шагом вводятся,
  как сгруппированы и что про них сказано. Одно описание на обе страницы.

  Раньше каждая страница держала свой список, и они разошлись: разные подписи
  одного поля («Перья» и «Перья (chainstay)», «Ход по паспорту» и «Ход, при
  котором заявлена геометрия»), разный шаг стека, короткая и длинная подсказка
  к проверке вилки. Хуже того, ссылка «Открыть в Fit Lab» собиралась по своему
  короткому списку из двенадцати полей: A2C, офсет новой вилки и поля проверки
  до Fit Lab не доезжали, хотя подпись у кнопки обещала «геометрия уедет как есть».

  Эталон подписей и групп — Fit Lab. Как расположить группы на экране, каждая
  страница решает сама: это раскладка, а не описание паспорта.

  Физики здесь нет — она в model.js. Классический скрипт, не модуль: с file://
  модули не грузятся. Подключается после model.js и до скрипта страницы.
*/
(function (global) {
  'use strict';

  /* Поле — [ключ, подпись, шаг, подсказка в пустом поле]. Кортеж, а не объект,
     потому что в таком виде страницы уже строят свои формы и таблицы подписей:
     описание встаёт на место их списков без переделки вёрстки. Подсказка null —
     страница ставит свою по умолчанию. */

  // основная геометрия из таблицы производителя
  const PASSPORT = [
    ['reach', 'Reach', 1, null],
    ['stack', 'Stack', 0.5, null],
    ['hta', 'Угол рулевой', 0.1, null],
    ['sta', 'Угол подседельной', 0.1, null],
    ['ht', 'Рулевой стакан', 1, null],
    ['st', 'Подседельная труба', 1, null],
    ['cs', 'Перья', 1, null],
    ['bbDrop', 'BB drop', 0.5, null],
    ['wb', 'Колёсная база', 1, 'или офсет'],
    ['travelRef', 'Ход по паспорту', 5, null]
  ];

  /* Офсет — не отдельная группа по смыслу, а альтернатива базе: солвер рамы
     ставит переднюю ось по одному из двух чисел. Бывают таблицы геометрии без
     базы — у трёх рам Hagen в данных владельца задан именно офсет. */
  const OFFSET = ['offset', 'Офсет вилки', 1, 'или база'];

  // замена вилки: в расчёт идут разность A2C и новый офсет
  const FORK_SWAP = [
    ['forkA2C', 'A2C штатной вилки', 1, 'не задан'],
    ['forkA2Cnew', 'A2C новой вилки', 1, 'не задан'],
    ['forkOffsetNew', 'Офсет новой вилки', 1, 'не задан']
  ];

  // обратная проверка: в расчёт не входит, только сверяет замеры рамы с железом
  const FORK_CHECK = [
    ['forkOffsetSpec', 'Офсет вилки по спеке', 1, 'не задан'],
    ['forkMeasLen', 'Замер: низ чашки → ось', 1, 'не задан']
  ];

  // ход и просадка — слайдеры: их крутят, разглядывая результат
  const SLIDERS = {
    travel: { label: 'Ход вилки', min: 60, max: 180, step: 5, unit: ' мм' },
    sag:    { label: 'SAG вилки', min: 0,  max: 40,  step: 1, unit: '%' }
  };

  const HINTS = {
    needFrontAxle: 'Рама не считается: нет ни колёсной базы, ни офсета вилки. Без одного из них переднюю ось не поставить, '
      + 'а подставлять число наугад модель не будет — это была бы уже другая рама.',
    forkCheck: 'Оба поля необязательны и в расчёт не входят — это сверка твоих замеров рамы с железом, которое стоит на велосипеде. '
      + '<b>Офсет по спеке</b> берётся из описания вилки. Модель выводит офсет из геометрии, и если они расходятся, виноват чаще всего угол рулевой: '
      + '0.1° угла стоит больше миллиметра офсета, а телефонный уровень врёт как раз на полградуса. Поэтому полезнее вывести угол из офсета, чем мерить его. '
      + '<b>Замер до оси</b> — рулеткой от низа чашки рулевой до оси переднего колеса. Он, наоборот, к углу почти нечувствителен и ловит ошибки в reach, '
      + 'стеке, базе и BB drop. Две проверки читают разные ошибки, поэтому вместе они сильнее любой из них.',
    forkSwap: 'Пусто — модель считает, что при смене хода A2C растёт 1:1, а офсет не меняется. Это верно для «накрутил ход на той же вилке» '
      + 'и неверно при смене модели: у двух вилок с одним ходом A2C расходится на 10–18 мм. '
      + 'Заполни оба A2C — и в расчёт пойдёт их разность. Именно разность: A2C меряется от кольца короны, а модель от низа стакана, '
      + 'и неизвестная высота нижней чашки в разности сокращается. Офсет подставляется напрямую. '
      + 'Ход при этом продолжает работать — но только на sag.'
  };

  /* Порядок полей рамы в ссылке Fit Lab (ключ f). Это формат уже разосланных
     ссылок: новые поля дописываются ТОЛЬКО в конец, иначе старые ссылки
     прочитаются со сдвигом. Fit Lab берёт отсюда же свой список, поэтому
     страница сравнения не может собрать ссылку в другом порядке. */
  const LINK_KEYS = ['reach', 'stack', 'hta', 'sta', 'ht', 'st', 'cs', 'bbDrop', 'wb', 'travelRef', 'travel', 'sag',
                     'forkA2C', 'forkA2Cnew', 'forkOffsetNew', 'forkOffsetSpec', 'forkMeasLen',
                     // с 2026-09-17: Fit Lab принимает офсет как альтернативу базе
                     'offset'];

  /* Основная сетка карточки рамы — одна на обе страницы: таблица геометрии
     сверху вниз, офсет сразу за базой, потому что это два способа задать одно и
     то же — переднюю ось. */
  const GRID = [...PASSPORT.slice(0, 9), OFFSET, ...PASSPORT.slice(9)];

  const ALL = [...PASSPORT, OFFSET, ...FORK_SWAP, ...FORK_CHECK];
  const KEYS = [...ALL.map(f => f[0]), 'travel', 'sag'];
  const field = key => ALL.find(f => f[0] === key) || null;
  const label = key => (SLIDERS[key] ? SLIDERS[key].label : (field(key) || [])[1]) || key;

  /* Ссылка, открывающая раму в Fit Lab. Уходит то, что ввёл человек: рама,
     заданная офсетом, приезжает с офсетом, а не с базой, выведенной за него.
     Кокпит, тело и посадка в ссылку не идут: там остаётся то, что у Fit Lab по
     умолчанию или в его пресетах. */
  function fitLabLink(b, wheelR, name) {
    const f = LINK_KEYS.map(k => b[k] == null || b[k] === '' ? '' : b[k]).join('~');
    return `fit-lab.html#w=${wheelR}&n=${encodeURIComponent(name || '')}&f=${f}`;
  }

  /* Строка под слайдерами: насколько ход отличается от паспортного и сколько
     миллиметров съедает просадка. Одна на обе страницы. */
  function travelNote(b) {
    const d = b.travel - b.travelRef;
    return [
      d === 0 ? 'ход паспортный' : `ход ${d > 0 ? '+' : ''}${d} мм от паспортного (${b.travelRef})`,
      b.sag ? `просадка ${(b.travel * b.sag / 100).toFixed(0)} мм` : 'без просадки = паспортная геометрия'
    ].join(' · ');
  }

  global.BikeFrame = { PASSPORT, OFFSET, GRID, FORK_SWAP, FORK_CHECK, SLIDERS, HINTS, LINK_KEYS, KEYS,
                       field, label, fitLabLink, travelNote };

})(typeof globalThis !== 'undefined' ? globalThis : this);
